const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const read = name => fs.readFileSync(path.join(__dirname,name),'utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'');
(async () => {
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  try {
    const page = await browser.newPage({viewport:{width:1280,height:1000}});
    await page.route('**/*',route => route.request().isNavigationRequest() && route.request().frame() === page.mainFrame() ? route.fulfill({body:'<!doctype html><body></body>',contentType:'text/html'}) : route.abort());
    for (const [url,file,dark] of [['/','home-sample.html',false],['/level/level-1/','level-sample.html',true],['/category/news/?level=level-2','level-sample.html',true],['/level/level-1/page/2/','level-sample.html',false],['https://www.daysinlevels.com/','days-home-sample.html',true],['https://daysinlevels.com/category/science/?level=level-2','days-home-sample.html',false]]) {
      await page.goto(url.startsWith('https:') ? url : `https://www.newsinlevels.com${url}`);
      const fixture = read(file);
      await page.setContent(fixture);
      const expected = await page.locator('.recent-news .news-block h3 a').count();
      const sourceHref = await page.locator('.recent-news .news-block h3 a').first().getAttribute('href');
      await page.evaluate(dark => { window.chrome = {storage:{local:{get:async () => ({nilSize:20,nilDark:dark}),set:async () => {}}}}; },dark);
      await page.addStyleTag({path:path.join(__dirname,'../extension/isolation.css')});
      for (const script of ['bootstrap.js','listing.js','reader.js']) await page.addScriptTag({path:path.join(__dirname,'../extension',script)});
      const host = page.locator('#nil-reader-host');
      await host.locator('.news-card').first().waitFor();
      assert.equal(await host.evaluate(el => el.shadowRoot),null);
      assert.equal(await page.evaluate(() => !!document.querySelector('#nil-reader-host .news-card h2')),true);
      await page.evaluate(() => {
        const popup = document.createElement('div'); popup.id='translation-popup'; popup.textContent='Translation'; popup.style.cssText='position:fixed;top:0;left:0;z-index:99999'; document.body.append(popup);
        const range = document.createRange(); range.selectNodeContents(document.querySelector('#nil-reader-host .news-card h2')); const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
      });
      assert.equal(await page.locator('#translation-popup').isVisible(),true);
      assert.equal(await page.evaluate(() => window.getSelection().toString().length > 0),true);
      assert.equal(await host.locator('.news-card').count(),expected);
      assert.equal(new URL(await host.locator('.news-card h2 a').first().getAttribute('href')).pathname,new URL(sourceHref).pathname);
      assert.equal(await host.locator('.news-card').first().locator('.levels a').count(),3);
      assert.equal(await host.locator('.pagination a').count(),7);
      assert.equal(await host.locator('.pagination [aria-current="page"]').count(),1);
      assert.equal(await host.locator('.reader').evaluate(el => el.classList.contains('dark')),dark);
      const before = await host.locator('main').boundingBox();
      await host.getByRole('button',{name:'文章分类 ▾'}).click();
      await host.locator('.category-nav:popover-open').waitFor();
      assert.equal((await host.locator('main').boundingBox()).y,before.y);
      await page.keyboard.press('Escape');
      assert.equal(await host.locator('.category-nav').evaluate(el => el.matches(':popover-open')),false);
      await host.getByRole('button',{name:'文章分类 ▾'}).click();
      await host.locator('h1').click();
      assert.equal(await host.locator('.category-nav').evaluate(el => el.matches(':popover-open')),false);
      await host.getByRole('button',{name:'文章分类 ▾'}).click();
      assert.equal(await host.locator('.category-nav a').count(),url.includes('daysinlevels') ? 7 : 8);
      if (url.includes('level-2')) assert.match(await host.locator('.category-nav a').first().getAttribute('href'),/level=level-2/);
      if (url === '/') await page.screenshot({path:path.join(__dirname,'../preview-list-desktop.png'),fullPage:true});
      await page.setViewportSize({width:390,height:844});
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true);
      if (url === '/') await page.screenshot({path:path.join(__dirname,'../preview-list-mobile.png'),fullPage:true});
      await host.getByRole('button',{name:'查看原网页',exact:true}).click();
      assert.equal(await page.evaluate(() => document.documentElement.classList.contains('nil-reading')),false);
      await host.getByRole('button',{name:'返回专注阅读',exact:true}).click();
      await page.setViewportSize({width:1280,height:1000});
    }
    await page.goto('https://www.daysinlevels.com/article/first-man-climbed-all-mountains-over-8000-meters-level-1/');
    await page.setContent(read('days-article-sample.html'));
    await page.evaluate(() => { window.chrome = {storage:{local:{get:async () => ({nilDark:true}),set:async () => {}}}}; });
    await page.addStyleTag({path:path.join(__dirname,'../extension/isolation.css')});
    for (const script of ['bootstrap.js','listing.js','reader.js']) await page.addScriptTag({path:path.join(__dirname,'../extension',script)});
    const days = page.locator('#nil-reader-host');
    await days.locator('h1').waitFor();
    assert.equal(await days.locator('.brand').textContent(),'Days in Levels');
    assert.equal(await days.locator('.levels a').count(),3);
    assert.equal(await days.locator('.vocabulary-row').count(),4);
    assert.equal(await days.locator('audio').count(),1);
    assert.equal(await days.locator('audio').evaluate(audio => getComputedStyle(audio).display),'block');
    assert.equal(await days.locator('audio').getAttribute('controls'),'');
    assert.equal(await days.locator('audio').getAttribute('autoplay'),null);
    await page.screenshot({path:path.join(__dirname,'../preview-days-article.png'),fullPage:true});
    await days.locator('audio').evaluate(audio => audio.dispatchEvent(new Event('error')));
    await days.getByText('音频加载失败或链接已过期，请刷新后重试。').waitFor();
    await days.getByRole('button',{name:'刷新页面并重试'}).waitFor();
    await page.goto('https://www.newsinlevels.com/contact/');
    await page.addScriptTag({path:path.join(__dirname,'../extension/bootstrap.js')});
    assert.equal(await page.evaluate(() => document.documentElement.classList.contains('nil-loading')),false);
    console.log('PASS: real home/level cards, category routing, pagination links, themes, mobile layout, original-page toggle, unsupported-page guard.');
  } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1;});
